'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { DRIVER_FILES, driverDirectory, validateDriverPackage } = require('./prepare-virtual-micro-driver');

function generatePayloadHashes(directory = driverDirectory(), root = path.resolve(__dirname, '..')) {
  const files = validateDriverPackage(directory);
  const hashes = Object.fromEntries(files.map((file, index) => [DRIVER_FILES[index],
    crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex').toUpperCase()]));
  const entries = Object.entries(hashes).map(([name, hash]) => `            ["${name}"] = "${hash}",`).join('\n');
  const source = `namespace VirtualMicroBroker;\n\n// Generated by scripts/generate-virtual-micro-payload-hashes.js.\ninternal static partial class DriverPayloadHashes\n{\n    internal static IReadOnlyDictionary<string, string> ExpectedSha256 { get; } =\n        new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase)\n        {\n${entries}\n        };\n}\n`;
  const target = path.join(root, 'native/virtual-micro-broker/DriverPayloadHashes.g.cs');
  fs.writeFileSync(target, source);
  return hashes;
}
if (require.main === module) {
  const hashes = generatePayloadHashes(process.argv[2]);
  if (process.argv[3]) fs.writeFileSync(process.argv[3], JSON.stringify(hashes, null, 2) + '\n');
}
module.exports = { generatePayloadHashes };
