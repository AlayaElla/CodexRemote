'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { AUDIO_DRIVER_FILES, audioDriverDirectory, validateAudioDriverPackage } = require('./prepare-virtual-audio-driver');

function generateAudioPayloadHashes(directory = audioDriverDirectory(), root = path.resolve(__dirname, '..')) {
  const files = validateAudioDriverPackage(directory);
  const hashes = Object.fromEntries(files.map((file, index) => [AUDIO_DRIVER_FILES[index],
    crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex').toUpperCase()]));
  const entries = Object.entries(hashes).map(([name, hash]) => `            [\"${name}\"] = \"${hash}\",`).join('\n');
  const source = `namespace VirtualMicroBroker;\n\n// Generated by scripts/generate-virtual-audio-payload-hashes.js.\ninternal static partial class AudioDriverPayloadHashes\n{\n    internal static IReadOnlyDictionary<string, string> ExpectedSha256 { get; } =\n        new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase)\n        {\n${entries}\n        };\n}\n`;
  const target = path.join(root, 'native/virtual-micro-driver-installer/AudioDriverPayloadHashes.g.cs');
  fs.writeFileSync(target, source);
  return hashes;
}
if (require.main === module) {
  const hashes = generateAudioPayloadHashes(process.argv[2]);
  if (process.argv[3]) fs.writeFileSync(process.argv[3], JSON.stringify(hashes, null, 2) + '\n');
}
module.exports = { generateAudioPayloadHashes };
